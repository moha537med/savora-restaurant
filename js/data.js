export let orders = JSON.parse(localStorage.getItem("orders")) || [];

export let confirmedOrders =
    JSON.parse(localStorage.getItem("confirmedOrders")) || [];


// === Add Order ===

export function addOrder(card) {

    const found = orders.find(order => order.id === card.id);

    if (found) {
        found.quantity++;
    } else {
        orders.push({
            ...card,
            quantity: 1
        });
    }

    localStorage.setItem("orders", JSON.stringify(orders));
}


// === Update Orders Count ===

export function updateOrdersCount() {

    const ordersNum = document.getElementById("ordersNum");

    if (!ordersNum) {
        return;
    }

    if (orders.length === 0) {
        ordersNum.style.display = "none";
        return;
    }

    ordersNum.style.display = "inline";
    ordersNum.textContent = orders.length > 10
        ? "+10"
        : orders.length;
}


// === Confirm Order ===

export function confirmOrder() {

    if (orders.length === 0) {
        return null;
    }

    const newOrder = {
        id: `SV-${Date.now()}`,
        items: [...orders],
        total: orders.reduce(
            (total, order) => total + order.price * order.quantity,
            0
        ),
        status: "confirmed",
        createdAt: new Date().toISOString()
    };

    confirmedOrders.push(newOrder);

    localStorage.setItem(
        "confirmedOrders",
        JSON.stringify(confirmedOrders)
    );

    orders.length = 0;

    localStorage.setItem(
        "orders",
        JSON.stringify(orders)
    );

    return newOrder;
}
